def add_note(
    key: str,
    title: str,
    folder: str,
    body: str = "",
    *,
    kind: str = "doc",
    tags: tuple[str, ...] = (),
    props: dict | None = None,
    sort: int = 0,
    source_key: str | None = None,
    wiki_slug: str | None = None,
    pinned: bool = False,
    minutes: int = 0,
) -> str:
    note_props = dict(props or {})
    if wiki_slug:
        note_props["wiki_page_id"] = uid(f"wiki:{wiki_slug}")
    if pinned:
        note_props["pinned"] = True
    NOTES.append(
        {
            "key": key,
            "id": uid(f"note:{key}"),
            "title": title,
            "body_md": body.strip(),
            "kind": kind,
            "folder": folder,
            "tags": tags,
            "props": note_props,
            "sort": sort,
            "source_key": source_key,
            "minutes": minutes,
        }
    )
    return key


